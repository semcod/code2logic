"""
Logic2Test - Generate tests from Code2Logic output files.

This package reads YAML, Hybrid YAML, or TOON format files generated by code2logic
and produces various types of tests (unit tests, integration tests, property tests).

Usage:
    from logic2test import TestGenerator

    generator = TestGenerator('project.c2l.yaml')
    generator.generate_unit_tests('tests/')
"""

from .generator import GenerationResult, GeneratorConfig, TestGenerator
from .parsers import LogicParser
from .templates import TestTemplate

def _resolve_version() -> str:
    """Installed metadata first; a source checkout reads the sibling pyproject.toml."""
    from importlib.metadata import PackageNotFoundError, version
    try:
        return version("logic2test")
    except PackageNotFoundError:
        import re
        from pathlib import Path
        pyproject = Path(__file__).resolve().with_name("pyproject.toml")
        match = re.search(r'^version\s*=\s*"([^"]+)"', pyproject.read_text(encoding="utf-8"), re.M) if pyproject.is_file() else None
        return match.group(1) if match else "0+unknown"


__version__ = _resolve_version()
__all__ = ["TestGenerator", "GeneratorConfig", "GenerationResult", "LogicParser", "TestTemplate"]
